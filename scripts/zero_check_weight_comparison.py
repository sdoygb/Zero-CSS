"""决定性对比：检查算子权重（决定硬件可行性）＋ Zero 归属

已算出的参数对比（同 d=16）：
  RM(3,8)  [[256, 70, 16]]  率 0.273
  RM(3,10) [[1024, 672, 16]] 率 0.656
  RM(3,12) [[4096, 3498, 16]] 率 0.854
  toric L=16 [[512, 2, 16]]  率 0.004
  ⇒ 参数上 AG/RM 完胜。但要看**代价**。

本文件算
  W1 RM(r,m) 稳定子生成元的**最大权重 / 平均权重**
  W2 拓扑码检查算子的权重（顶点度数／面边长）
  W3 两者的"局域性"对比：权重是否随参数增长
  W4 Zero 归属：RM 的递归张量积与 Zero 的 M_2^⊗E 是否形式吻合
"""
from __future__ import annotations

import itertools
from math import comb

import numpy as np


def rm_generators(m, r):
    """RM(r,m) 的生成元行（单形式求值向量），返回 (n, rows)。"""
    n = 1 << m
    rows = []
    for mask in range(1 << m):
        if mask.bit_count() <= r:
            rows.append([1 if (col & mask) == mask else 0 for col in range(n)])
    return n, np.array(rows, dtype=np.uint8)


def main() -> None:
    print("=" * 94)
    print("决定性对比：检查算子权重（硬件可行性的关键）")
    print("=" * 94)

    print("\n[W1] RM(r,m) 生成元的权重")
    print("    %-12s %6s %6s %8s %8s %10s" % ("码", "n", "生成元数", "最小权重", "最大权重", "平均权重"))
    for m in (4, 6, 8, 10):
        for r in (1, 2, 3):
            if 2 * r >= m - 1 or r >= m:
                continue
            n, G = rm_generators(m, r)
            if G.shape[0] > 20000:
                continue
            w = G.sum(axis=1)
            print("    RM(%d,%-6d) %6d %6d %8d %8d %10.2f"
                  % (r, m, n, G.shape[0], w.min(), w.max(), w.mean()))
    print("    ⇒ 最小权重 = 2^(m−r)（随 m 指数增），最大权重 = 2^m（全一向量）")
    print("    ⚠ RM(1,m)：生成元含**全一向量**（权重 2^m）与单点向量（权重 1）")
    print("      —— 全一向量是**非局域**的（碰所有比特）！")

    print("\n[W2] 拓扑码检查算子的权重（Zero 原生）")
    print("    %-20s %10s %10s %10s" % ("码", "X 检查权重", "Z 检查权重", "是否局域"))
    for p, q, name in ((4, 4, "平坦 {4,4}"), (5, 4, "双曲 {5,4}"), (7, 3, "双曲 {7,3}")):
        print("    %-20s %10d %10d %10s" % (name, q, p, "✓ 常数"))
    print("    ⇒ 权重 = 顶点度数 q、面边长 p，**与码长无关**（Z1 定理 1 的局域性）")

    print("\n[W3] 局域性对比（权重是否随参数增长）")
    print("    %-24s %-22s %-22s" % ("族", "检查权重", "随 n 增长？"))
    print("    %-24s %-22s %-22s" % ("RM(r,m)（AG 类）", "2^(m−r) … 2^m", "**是**（指数）"))
    print("    %-24s %-22s %-22s" % ("toric / 双曲表面码", "p, q（常数）", "**否**（常数）"))
    print("    %-24s %-22s %-22s" % ("HGP（qLDPC 主流）", "H 的行/列权重", "常数（若 H 稀疏）"))

    print("\n[W4] Zero 归属：RM 的结构与 Zero 原语的关系")
    print("""
    RM(r,m) 的定义：在 F_2^m 的全部点上，求值次数 ≤ r 的多项式。
    其生成元可写成**递归张量积**：
        G(r,m) = [[G(r,m−1), G(r,m−1)], [0, G(r−1,m−1)]]
      ⇒ 每个生成元 = 若干 σx 型算子的**张量积**（m 个二进制指标）。

    Zero 的原生结构（定理 F）：
        每条边一个二元算符空间 {I, F_e, Z_e, F_eZ_e} ≅ M_2
        全局代数 = M_2^⊗E（不同边对易）
      ⇒ **递归张量积在 Zero 里形式上存在**（F4：维数 4^E）

    但关键差别：
      · Zero 的张量积因子标号 = **图的边**（有局域结构：顶点/面）✓
      · RM 的张量积因子标号 = **F_2^m 的坐标**，且生成元含**全一向量**
        （权重 2^m ⇒ 碰全部比特）⇒ **没有局域结构** ✗

    ⇒ **RM 的"张量积"与 Zero 的"张量积"不是同一个东西**：
      前者是坐标张量积（无几何），后者是图的边张量积（有局域性）。
      所以 **AG/RM 不能从 Zero 原生推出**——差一个"局域结构"。
    """)

    print("=" * 94)
    print("最终对比表")
    print("=" * 94)
    print("""
    ┌────────────────────┬──────────────┬──────────────┬──────────────┐
    │ 指标                │ AG/RM        │ toric        │ 双曲表面码    │
    ├────────────────────┼──────────────┼──────────────┼──────────────┤
    │ 同 d=16 的码率      │ 0.656        │ 0.004        │ ~0.36        │
    │ 检查算子权重        │ 8 … 2^m      │ 4（常数）     │ p（常数）     │
    │ 局域性（2D 近邻）   │ ✗ 需长程      │ ✓            │ ✓            │
    │ 距离尺度            │ d 常数       │ d ~ L        │ d ~ log n    │
    │ Zero 原生性         │ ✗（借代数几何）│ ✓ 全原生      │ ✓ 全原生      │
    │ 旧理论路线          │ ✓（目标）     │ —            │ —            │
    └────────────────────┴──────────────┴──────────────┴──────────────┘

    **纠错能力（参数）**：AG/RM > 双曲表面码 > toric
    **硬件可行性**：toric ≈ 双曲 > AG/RM（AG 需长程连接）
    **Zero 原生性**：toric = 双曲 >> AG/RM（AG 借外部代数几何）
    """)


if __name__ == "__main__":
    main()
