#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""双曲表面码在 χ≈0 极限下的参数：能否追上 AG/RM？

关键事实（已算）
  · 固定 (p,q)：k ∝ g ∝ n，但 d ~ log n（长环长度随 n 对数增长）
  · 允许 (p,q) 也增长（χ → 0⁻ 的"几乎平坦"极限）：d 可增长

本文件算
  G1 固定 (p,q) 下 k 与 d 的标度
  G2 χ ≈ 0 极限下的 k、d、检查权重
  G3 与 AG/RM 的最终对比（同 n 下的 k，或同 d 下的率）
"""
from __future__ import annotations

import math


def hyperbolic(p, q, g):
    """亏格 g 的 {p,q} 复形：2E = pF = qV，χ = 2 − 2g。"""
    # V − E + F = 2 − 2g，且 E = pF/2, V = pF/q
    # ⇒ pF/q − pF/2 + F = 2 − 2g
    # ⇒ F (p/q − p/2 + 1) = 2 − 2g
    coef = p / q - p / 2 + 1
    if coef >= 0:
        return None
    F = (2 - 2 * g) / coef
    E = p * F / 2
    V = p * F / q
    return V, E, F


def main() -> None:
    print("=" * 96)
    print("双曲表面码的两个极限")
    print("=" * 96)

    print("\n[G1] 固定 (p,q)：k ∝ n，但 d ~ log n")
    print("    %-14s %7s %9s %7s %10s %8s %8s" % ("{p,q}", "g", "n=2E", "k≈2g", "R=k/n", "检查权重", "d~log n"))
    for p, q in ((5, 4), (7, 3)):
        for g in (10, 100, 1000, 10000):
            r = hyperbolic(p, q, g)
            if not r:
                continue
            V, E, F = r
            n = 2 * E
            print("    {%d,%d}%8s %7d %9.0f %7d %10.3f %8s %8.1f"
                  % (p, q, "", g, n, 2 * g, 2 * g / n, "%d,%d" % (p, q), 0.4 * math.log(n)))

    print("\n[G2] χ ≈ 0 极限：p, q 也增长（几乎平坦）")
    print("    思路：取 χ = 2 − 2g 很小而 p, q 大 ⇒ F 大而 (p,q) 大")
    print("    %-16s %7s %9s %9s %8s %10s" % ("{p,q}", "g", "n", "k≈2g", "R", "检查权重"))
    for p, q in ((100, 100), (1000, 1000), (100, 102), (1000, 1002)):
        coef = p / q - p / 2 + 1
        if coef >= 0:
            print("    {%d,%d}: coef=%.4f ≥ 0（非双曲，跳过）" % (p, q, coef))
            continue
        for g in (2, 20):
            r = hyperbolic(p, q, g)
            if not r:
                continue
            V, E, F = r
            n = 2 * E
            print("    {%d,%d}%6s %7d %9.0f %9d %8.3f %10s"
                  % (p, q, "", g, n, 2 * g, 2 * g / n, "%d,%d" % (p, q)))

    print("\n" + "=" * 96)
    print("[G3] 最终对比：同 n≈1000 下的 k（物理比特数相同）")
    print("=" * 96)
    print("    %-34s %8s %8s %8s %10s" % ("方案", "n", "k", "R", "检查权重"))
    rows = [
        ("AG/RM: RM(3,10) [[1024,672,16]]", 1024, 672, "8…1024"),
        ("AG/RM: RM(2,10) [[1024,912,8]]", 1024, 912, "256…1024"),
        ("toric L=16 [[512,2,16]]", 512, 2, "4"),
        ("toric L=32 [[2048,2,32]]", 2048, 2, "4"),
        ("双曲 {5,4} g=61 [[~2400,122,~3]]", 2400, 122, "4,5"),
        ("双曲 {5,4} g≈25 (n≈1000)", 1000, 50, "4,5"),
    ]
    for name, n, k, w in rows:
        print("    %-34s %8d %8d %8.3f %10s" % (name, n, k, k / n, w))

    print("\n" + "=" * 96)
    print("结论：谁纠错更好？—— 取决于你看哪个轴")
    print("=" * 96)
    print("""
    ┌────────────────┬───────────────┬───────────────┬───────────────┐
    │ 轴              │ AG/RM          │ toric          │ 双曲固定(p,q) │
    ├────────────────┼───────────────┼───────────────┼───────────────┤
    │ 码率 R          │ 0.66–0.98      │ → 0            │ ~0.05         │
    │ 距离 d          │ 常数（8,16…）  │ ~L（可任意大） │ ~log n        │
    │ 同 d=16 的 R    │ 0.656          │ 0.004          │ 极低（需 n~e^40）│
    │ 检查权重        │ 8…2^m（指数）  │ 4（常数）      │ p（常数）     │
    │ 2D 近邻可行     │ ✗              │ ✓              │ ✓             │
    │ Zero 原生       │ ✗              │ ✓              │ ✓             │
    └────────────────┴───────────────┴───────────────┴───────────────┘

    **"纠错能力"（码率×距离的联合）**：AG/RM 明显更好。
      同 d=16：AG/RM 率 0.656，toric 率 0.004 —— 差 160 倍。
    **但 AG/RM 的代价是检查权重指数增长** ⇒ 需要长程连接 ⇒
      2D 近邻硬件（超导）不可行；这是旧理论 10.84 自己承认的。

    **Zero 的定位**：
      · Zero 原生 → 拓扑码（检查权重常数、局域）——纠错参数**不如** AG/RM
      · AG/RM 需要**外部的代数几何**（F_2 上的曲线／RM 递归），Zero 里没有
      ⇒ 若目标只是"纠错更好"，AG/RM 胜；若目标是"Zero 原生 + 硬件可行"，拓扑码胜。
    """)


if __name__ == "__main__":
    main()
